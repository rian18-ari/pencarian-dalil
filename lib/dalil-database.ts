const STOPWORDS = new Set([
  'dalil', 'tentang', 'ayat', 'hadis', 'hadits', 'hukum', 'mengenai', 'apa', 'bagaimana',
  'sebutkan', 'tolong', 'bacaan', 'yang', 'dan', 'di', 'ke', 'dari', 'untuk', 'pada', 'adalah'
]);

export function findLocalVerifiedDalil(query: string, filter: 'all' | 'quran' | 'hadits' = 'all'): DalilItem[] {
  const normalized = (query || '').toLowerCase().trim();
  if (!normalized) return [];

  // Extract keywords by filtering stopwords
  const tokens = normalized
    .replace(/[^\w\s]/g, ' ')
    .split(/\s+/)
    .filter(w => w.length >= 2);

  const keywords = tokens.filter(w => !STOPWORDS.has(w));
  const searchTerms = keywords.length > 0 ? keywords : tokens;

  if (searchTerms.length === 0) return [];

  interface ScoredItem {
    item: DalilItem;
    score: number;
  }

  const scored: ScoredItem[] = [];

  for (const item of VERIFIED_DALIL_DATABASE) {
    if (filter !== 'all' && item.sourceType !== filter) continue;

    const topicKeywords = (item.topicKeywords || []).map(k => k.toLowerCase());
    const reference = item.reference.toLowerCase();
    const surahOrBookName = item.surahOrBookName.toLowerCase();
    const translation = item.translationId.toLowerCase();
    const explanation = item.relevanceExplanation.toLowerCase();

    let score = 0;

    for (const term of searchTerms) {
      // High score for exact keyword in topicKeywords
      if (topicKeywords.some(k => k.includes(term) || term.includes(k))) {
        score += 15;
      }
      if (surahOrBookName.includes(term) || reference.includes(term)) {
        score += 10;
      }
      if (explanation.includes(term)) {
        score += 5;
      }
      if (translation.includes(term)) {
        score += 4;
      }
    }

    // Direct match against whole query string
    if (normalized.length > 3) {
      if (topicKeywords.some(k => normalized.includes(k))) score += 20;
      if (explanation.includes(normalized)) score += 10;
      if (translation.includes(normalized)) score += 8;
    }

    if (score > 0) {
      scored.push({ item, score });
    }
  }

  // Sort descending by score
  scored.sort((a, b) => b.score - a.score);

  return scored.map(s => s.item);
}
